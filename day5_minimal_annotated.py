# -*- coding: utf-8 -*-
"""
day5 最小版【带完整注释】

这份文件和 day5_minimal.py 的代码完全一样，只是每一行都加了注释。
先看懂这份，再回头看 day5_minimal.py 的纯净版，最后目标是把纯净版默写出来。

────────────────────────────────────────────────────────────────────────
【命名规律】全世界通用的约定，看懂这套就能读懂大部分深度学习代码：

    W    Weight       权重（矩阵，大写）
    b    bias         偏置
    z    激活【前】的线性输出（加权和）
    a    激活【后】的输出（activation）
    dX   损失对 X 的梯度（derivative）—— 形状一定和 X 完全相同
    X    输入矩阵（多样本）；y 真实标签
    下标 1 / 2        第几层（论文里常写成上标 W^[1]、W^[2]）

【形状解码】那些数字分别代表什么

    400 = 样本数            2 = 输入特征数（坐标 x, y）
     16 = 隐藏层神经元数      1 = 输出个数（二分类只要 1 个概率）
    网络规模：2 → 16 → 1

【数据流】

    前向： X → z1 → a1 → z2 → a2 → loss          （特征维度 2→16→1 变化，样本数 400 不变）
    反向： loss → dz2 → dW2,db2,dz1 → dW1,db1    （形状原路返回）

【六条规律】

    1. 先看形状      形状对了逻辑基本就对；梯度形状必须 == 参数形状
    2. @  vs  *      @ 是矩阵乘法，* 是逐元素相乘，完全不同
    3. np.c_ / np.r_ c_ 加列（竖着并排），r_ 加行（首尾相接）
    4. .mean(0)      数字是"压掉哪一维"；mean(0) = 对样本求平均
    5. reshape(-1)   -1 的意思是"这一维你帮我算"
    6. 广播          形状不同也能算，但错了【不报错】——要格外小心
────────────────────────────────────────────────────────────────────────
"""
import numpy as np                          # numpy 的惯例别名

# ============================================================================
# 1. 造数据：两个交错的新月
# ============================================================================
# 为什么不用线性可分的数据？因为一条直线就能分开的数据不需要隐藏层，逻辑回归
# 就够了。必须用"一条直线分不开"的数据，才看得出神经网络的价值。

np.random.seed(0)                           # 固定随机种子。否则每次运行的初始权重
                                            # 和噪声都不同，结果无法复现、无法对比

t = np.linspace(0, np.pi, 200)              # 在 [0, π] 之间等距取 200 个点 → (200,)
                                            # linspace = 按【个数】取，且一定包含终点
                                            # t 是角度参数，只用于造数据，训练时不参与

# 上半月：每个点是 (cos t, sin t)，就是单位圆的上半圈 → (200, 2)
#   np.cos(t) / np.sin(t)  对 t 逐元素求值，形状仍是 (200,)
#   np.c_[A, B]            按【列】拼接：两个 (200,) 并排成 (200,2)，第0列是A，第1列是B
#   验证：t=0 时第 0 行是 [1,0]；t=π/2 时第 100 行是 [0,1]
# 下半月：把圆翻转 + 平移，和上半月咬合成"太极图" → (200, 2)
#   np.vstack([A, B])      按【行】堆叠：两个 (200,2) 上下摞成 (400, 2)
#   结果：前 200 行是类别 0，后 200 行是类别 1
X = np.vstack([np.c_[np.cos(t),     np.sin(t)],
               np.c_[1 - np.cos(t), .5 - np.sin(t)]])

X = X + np.random.normal(0, .12, X.shape)   # 给每个坐标加高斯噪声（均值0，标准差0.12）
                                            # np.random.normal(均值, 标准差, 形状)
                                            # 加噪声后数据不再是完美曲线，更接近真实情况
                                            # 也让模型无法"背下"每个点，才有泛化可言

# 标签：200 个 0 接 200 个 1，再改成列向量
#   np.zeros(200) / np.ones(200)  全 0 / 全 1 的一维数组
#   np.r_[A, B]                   按行拼接，一维时就是首尾相接 → (400,)
#   .reshape(-1, 1)               变成 (400,1)。-1 表示"这一维你帮我算"
# ★ 为什么必须变成 (400,1)：
#     第 31 行要算 a2 - y，而 a2 是 (400,1)。若 y 保持 (400,)：
#         (400,1) 和 (400,) 广播 → (400,400)  一个 16 万元素的矩阵
#     而且【完全不报错】！这是 NumPy 最经典的坑。
y = np.r_[np.zeros(200), np.ones(200)].reshape(-1, 1)

# ============================================================================
# 2. 初始化参数：2 → 16 → 1
# ============================================================================
# 这四个变量就是模型"学到"的全部内容：32 + 16 + 16 + 1 = 65 个数字。
# 训练完只要保存这 65 个数，模型就完整了。

# W1 (2,16)：2 个输入 → 16 个隐藏神经元
#   np.random.randn(shape)  标准正态分布随机数（均值0、方差1），
#                           等价于 np.random.normal(0, 1, shape)
#   * .5                    把标准差缩到 0.5。为什么？让初始的 z1 别太大，
#                           否则 tanh 一开始就进入饱和区，那里导数接近 0，
#                           梯度传不回去，网络学不动
# b1 (16,)：16 个偏置，初始化为 0
# ★ 权重不能全为 0，偏置可以：
#     权重全 0 的话，16 个隐藏神经元输出完全相同 → 梯度也相同 → 更新后还是相同，
#     "16 个神经元"会退化成一个。随机权重的作用就是打破这种对称性。
W1, b1 = np.random.randn(2, 16) * .5, np.zeros(16)

# W2 (16,1)：16 个隐藏神经元 → 1 个输出。同样缩放，防止输出层饱和
# b2 (1,) ：只有 1 个输出，所以只有 1 个偏置
W2, b2 = np.random.randn(16, 1) * .3, np.zeros(1)

# sigmoid 函数：把任意实数压到 (0,1) 区间，当概率用
#   lambda z: ...            匿名函数，完全等价于
#                                def sig(z): return ...
#                             只是省了个函数名
#   np.exp(-z)               逐元素求 e^(-z)
#   np.clip(z, -500, 500)    裁剪：小于-500的变-500，大于500的变500
#     为什么需要？如果 z = -1000，np.exp(1000) 会溢出成 inf，再算下去可能得到
#     nan，整个训练就毁了。500 是安全余量：float64 上限约 1.8e308，e^709 就接近溢出。
#     而 sigmoid 在 |z|>500 时输出已经是 0 或 1，裁掉完全不影响结果。
sig = lambda z: 1 / (1 + np.exp(-np.clip(z, -500, 500)))

# ============================================================================
# 3. 训练循环
# ============================================================================
# 这是【全批量梯度下降】：每一轮都用全部 400 个样本算一次梯度。

for epoch in range(3000):                   # epoch = 当前轮次，取值 0 ~ 2999

    # ---------------------- 前向传播 ----------------------
    # X @ W1 : (400,2) @ (2,16) = (400,16)
    #   @ 是矩阵乘法运算符（等价 np.matmul）。规则：内维必须相等(2=2)，结果取外维
    #   ★ @ 是矩阵乘法，* 是逐元素相乘，两者完全不同
    # + b1   : b1 是 (16,)，【广播】到每一行 —— 400 个样本各自加上同一组偏置
    # tanh   : 逐元素双曲正切，压到 (-1,1)
    # ★ 这一行就是"隐藏层" = 线性变换 + 非线性激活。
    #   非线性是关键：没有它，再多层也等价于一层线性模型。
    a1 = np.tanh(X @ W1 + b1)               # a1 (400,16)  隐藏层输出（网络对数据的内部表示）

    # a1 @ W2 : (400,16) @ (16,1) = (400,1)
    # + b2    : (1,) 广播
    # sig     : 变成 0~1 的概率
    a2 = sig(a1 @ W2 + b2)                  # a2 (400,1)   最终预测：属于类别 1 的概率

    # ---------------------- 损失：二元交叉熵 ----------------------
    # 拆开看： y * log(a2)  +  (1-y) * log(1-a2)
    #   利用 y 只有 0/1 的特点，用【乘法代替 if-else】：
    #     y=1 时 第一项 = log(a2)   （只看"预测为 1 的概率"），第二项变 0
    #     y=0 时 第一项 = 0，第二项 = log(1-a2) 生效
    #   这就是"只看正确答案那一项"的向量化写法
    # 1e-12  : 防止 log(0) = -inf
    # np.mean: 对 400 个样本取平均 → 得到一个【标量】
    # 前面的负号: log 是负的，取负让损失为正数
    loss = -np.mean(y * np.log(a2 + 1e-12) + (1 - y) * np.log(1 - a2 + 1e-12))

    # ---------------------- 反向传播（链式法则）----------------------
    # dz2 = ∂L/∂z2 = "预测 - 真实"
    # 这不是巧合 —— 交叉熵和 sigmoid 被设计成一对，导数正好化简成这个形式
    dz2 = a2 - y                             # (400,1)

    # dW2 = a1.T @ dz2 / 400
    #   a1.T 是 (16,400)，@ dz2 (400,1) → (16,1) —— 正好是 W2 的形状 ✓
    #   /400 是因为前面 loss 用了 mean，梯度也要相应平均
    # db2 = dz2.mean(0)
    #   axis=0 表示"压掉第 0 维"，也就是对 400 个样本求平均 → (1,) ✓
    # ★ 通用规律：每个参数的梯度形状，必须和该参数本身完全一致
    dW2, db2 = a1.T @ dz2 / 400, dz2.mean(0)

    # dz1 = (dz2 @ W2.T) * (1 - a1**2)
    #   W2.T 是 (1,16)，dz2(400,1) @ (1,16) → (400,16)
    #     含义：把输出层的误差，按各条连接的权重"分发"回隐藏层，权重大的责任大
    #   (1 - a1**2) 是 tanh 的导数
    #     因为 a1 = tanh(z1)，而 d(tanh)/dz = 1 - tanh²
    #   ★ 重点是那个 * —— 逐元素相乘，不是矩阵乘法
    dz1 = (dz2 @ W2.T) * (1 - a1 ** 2)      # (400,16)，和 a1 同形状 ✓

    # 注意 dW 的公式都是「输入.T @ 误差」—— 这条规律贯穿所有层
    dW1, db1 = X.T @ dz1 / 400, dz1.mean(0)  # (2,16) 和 (16,)，分别等于 W1、b1 的形状 ✓

    # ---------------------- 梯度下降 ----------------------
    # .5 是【学习率】。沿梯度的【反方向】走一小步：
    #   梯度指向损失增大的方向，我们要让它变小，所以用减号
    #   乘一个小数是怕步子太大跨过最低点，导致来回震荡甚至发散
    W1, b1 = W1 - .5 * dW1, b1 - .5 * db1
    W2, b2 = W2 - .5 * dW2, b2 - .5 * db2

    # ---------------------- 每 1000 轮报告一次 ----------------------
    # epoch % 1000 == 0   % 是取余，每 1000 轮触发一次
    # a2 > .5             逐元素比较，返回【布尔数组】。概率 > 0.5 判为类别 1
    # == y                和真实标签比较：预测对了是 True，错了是 False
    # .mean()             布尔数组求平均 = True 的比例 =【准确率】
    #                     （True 当 1、False 当 0，这是个常用技巧）
    # f-string            {epoch:4d} 整数占4位右对齐；{loss:.4f} 保留4位小数
    if epoch % 1000 == 0:
        print(f"epoch {epoch:4d}   loss {loss:.4f}   acc {((a2 > .5) == y).mean():.3f}")

print(f"最终       loss {loss:.4f}   acc {((a2 > .5) == y).mean():.3f}")

# ============================================================================
# 变量速查表
# ============================================================================
# 【数据】
#   t        (200,)     角度参数 0→π，只用于造数据
#   X        (400,2)    输入：400 个样本，每个 2 个特征（坐标）
#   y        (400,1)    标签：0 或 1
#
# 【参数】—— 模型"学到"的就是这四个
#   W1       (2,16)     第一层权重
#   b1       (16,)      第一层偏置
#   W2       (16,1)     第二层权重
#   b2       (1,)       第二层偏置
#
# 【前向中间量】
#   a1       (400,16)   隐藏层输出（激活后）      <- 对应"激活前"本该叫 z1，本脚本没单独取名
#   a2       (400,1)    最终预测概率
#   loss     标量        全批次平均损失 —— 唯一要让它变小的东西
#
# 【反向梯度】—— 每个 dX 的形状都和 X 相同
#   dz2      (400,1)    ∂L/∂z2
#   dW2      (16,1)     ∂L/∂W2      db2  (1,)
#   dz1      (400,16)   ∂L/∂z1
#   dW1      (2,16)     ∂L/∂W1      db1  (16,)
#
# 【其他】
#   sig      函数        sigmoid
#   epoch    整数        当前轮次
#   .5       常数        学习率（正式代码应该起名叫 lr）
#   400      常数        样本数（这里是硬编码，正式代码应该写 len(X)）
#   1e-12    常数        防止 log(0)
#
# ────────────────────────────────────────────────────────────────────────
# 【最容易混淆的三组】
#   a1 vs a2    a1 是隐藏层输出（16维内部表示）；a2 是最终预测（1维概率）。
#               只有 a2 要和 y 比较。
#   dW1 vs W1   dW1 是梯度（该往哪走）；W1 是参数（现在在哪）。
#               第 36 行用 W1 - lr*dW1 把两者结合起来。
#   z vs a      z 是激活前（可正可负、无界）；a 是激活后（压进固定区间）。
#               反向时先算 dz，再乘激活函数的导数 —— 因为导数公式是关于 a 的。
# ────────────────────────────────────────────────────────────────────────
